import os
import sys
import logging
import threading
import time
from pathlib import Path
from flask import Flask, request, jsonify
import requests

from google.adk.runners import Runner
from google.adk.sessions import InMemorySessionService
from google.genai import types
from jwt_auth import decode_jwt_token_with_reason, extract_jwt_from_request


# Import your existing ADK app definition
from workflow_agents.agent import app as adk_app

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("agent_movie_script")

app = Flask(__name__)
PORT = int(os.environ.get("PORT", 8010))
ROUTER_URL = os.environ.get("ROUTER_URL", "http://agents_router:8004")

# Initialize ADK runner with in-memory session management
session_service = InMemorySessionService()
runner = Runner(app=adk_app, session_service=session_service, auto_create_session=True)

# -------------------------------------------------------------------------
# 1. Health Check Endpoint (Required by Agents Router)
# -------------------------------------------------------------------------
@app.route("/health", methods=["GET"])
def health():
    return jsonify({
        "status": "healthy",
        "service": "agent-movie-script",
        "port": PORT,
        "role": "Movie Script & Screenplay Creation Specialist"
    }), 200

# -------------------------------------------------------------------------
# 2. Agent Chat Endpoint (Required by Agents Router)
# -------------------------------------------------------------------------
@app.route("/api/agent/chat", methods=["POST"])
def chat():
    data = request.json or {}
    message = data.get("message", "")
    if not message:
        return jsonify({"error": "Empty message prompt"}), 400

    conv_id = data.get("conversation_id", f"session-{int(time.time())}")
    # -------------------------------------------------------------
    # 1. Get Token & Authenticate
    # -------------------------------------------------------------
    token = extract_jwt_from_request(request)
    if not token:
        logger.warning("Rejected chat request: Missing authentication token")
        return jsonify({"error": "Unauthorized: Missing authentication token"}), 401

    payload, auth_msg = decode_jwt_token_with_reason(token)
    if not payload:
        logger.warning(f"Rejected chat request: {auth_msg} (token prefix: {token[:20]}...)")
        return jsonify({"error": f"Unauthorized: {auth_msg}"}), 403

    # -------------------------------------------------------------
    # 2. Use Authenticated Identity in ADK
    # -------------------------------------------------------------
    # Extract verified user email from token payload
    user_id = payload.get("email", "authenticated_user")
    logger.info(f"Authenticated user: {user_id} (domain: {payload.get('domain')})")

    logger.info(f"Executing movie script workflow for query: '{message[:60]}...'")

    try:
        # Run the ADK workflow
        events = runner.run(
            user_id=user_id,
            session_id=conv_id,
            new_message=types.Content(
                role="user",
                parts=[types.Part.from_text(text=message)]
            )
        )

        # Collect text generated by the agent team
        collected_responses = []
        for event in events:
            if event.content and event.content.parts:
                for part in event.content.parts:
                    if getattr(part, "text", None):
                        collected_responses.append(part.text)

        full_response = "\n\n".join(collected_responses).strip()
        if not full_response:
            full_response = "Movie concept and plot outline processed successfully."

        return jsonify({
            "response": full_response,
            "conversation_id": conv_id,
            "model": os.getenv("MODEL", "gemini-2.5-flash"),
            "role": "Movie Script Creator"
        }), 200

    except Exception as e:
        logger.error(f"Error during workflow execution: {e}", exc_info=True)
        return jsonify({"error": str(e)}), 500

if __name__ == "__main__":
    app.run(host="0.0.0.0", port=PORT)
