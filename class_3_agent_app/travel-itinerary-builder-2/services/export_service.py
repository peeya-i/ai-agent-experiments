"""Export utilities for generating text and PDF downloads of itineraries."""
import io
from typing import Dict, Any

def generate_text_itinerary(state: Dict[str, Any]) -> str:
    user_input = state.get("user_input", {})
    itinerary = state.get("current_itinerary", {})
    schedule = itinerary.get("schedule", [])
    cost_breakdown = itinerary.get("cost_breakdown", {})

    lines = []
    lines.append("=" * 60)
    lines.append(f"  TRAVEL ITINERARY: {user_input.get('destination', '').upper()}")
    lines.append("=" * 60)
    lines.append(f"Origin:          {user_input.get('origin', 'N/A')}")
    lines.append(f"Departure Date:  {user_input.get('departure_date') or 'Flexible'}")
    lines.append(f"Duration:        {user_input.get('days', 1)} Days")
    lines.append(f"Target Budget:   ${float(user_input.get('budget', 0.0)):,.2f}")
    lines.append(f"Estimated Cost:  ${float(itinerary.get('total_estimated_cost', 0.0)):,.2f}")
    lines.append(f"Budget Status:   {'APPROVED' if state.get('budget_approved') else 'BUDGET EXCEEDED'}")
    if user_input.get("interests"):
        lines.append(f"Interests:       {', '.join(user_input.get('interests', []))}")
    lines.append("-" * 60)

    # Transit & Accommodation
    flight = itinerary.get("selected_flight", {})
    hotel = itinerary.get("selected_hotel", {})
    lines.append("\n[LOGISTICS & ACCOMMODATION]")
    if flight:
        lines.append(f"• Transport: {flight.get('carrier', 'Flight')} ({flight.get('route', 'Transit')}) - ${flight.get('estimated_cost', 0):,.2f}")
    if hotel:
        lines.append(f"• Lodging:   {hotel.get('name', 'Hotel')} ({hotel.get('neighborhood', 'Area')}) - ${hotel.get('nightly_rate', 0):,.2f}/night")
    lines.append(f"• Cost Breakdown: Flights ${cost_breakdown.get('flight', 0):,.2f} | Lodging ${cost_breakdown.get('lodging', 0):,.2f} | Activities ${cost_breakdown.get('activities', 0):,.2f}")
    lines.append("-" * 60)

    # Schedule
    lines.append("\n[DAY-BY-DAY SCHEDULE]")
    for day in schedule:
        day_cost = float(day.get("estimated_cost", 0.0))
        lines.append(f"\n--- DAY {day.get('day')}: {day.get('neighborhood_focus', 'City Exploration').upper()} | Estimated Cost: ${day_cost:,.2f} ---")
        if day.get("insider_tip"):
            lines.append(f"  Insider Tip: {day.get('insider_tip')}")
        for ev in day.get("events", []):
            cost_str = f"${float(ev.get('estimated_cost', 0)):,.2f}" if float(ev.get("estimated_cost", 0)) > 0 else "FREE"
            dur_str = f"{float(ev.get('duration_hours', 1.0)):.1f} hrs"
            loc_str = ev.get("location", "Local Area")
            lines.append(f"  • [{ev.get('time_slot', 'Activity')}] {ev.get('name')} ({cost_str})")
            lines.append(f"      Category: {ev.get('category', 'Experience')} | Duration: {dur_str} | Location: {loc_str}")
            if ev.get("description"):
                lines.append(f"      Details: {ev.get('description')}")

    if state.get("critic_feedback"):
        lines.append("\n" + "-" * 60)
        lines.append(f"[AGENT OPTIMIZER NOTES]\n{state.get('critic_feedback')}")

    lines.append("\n" + "=" * 60)
    lines.append("  Generated by Autonomous Multi-Agent Travel Itinerary Builder")
    lines.append("=" * 60)
    return "\n".join(lines)


def generate_pdf_itinerary(state: Dict[str, Any]) -> io.BytesIO:
    """Generates a styled PDF using ReportLab or fallback."""
    user_input = state.get("user_input", {})
    itinerary = state.get("current_itinerary", {})
    schedule = itinerary.get("schedule", [])
    cost_breakdown = itinerary.get("cost_breakdown", {})

    pdf_buffer = io.BytesIO()

    try:
        from reportlab.lib.pagesizes import letter
        from reportlab.lib import colors
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

        doc = SimpleDocTemplate(
            pdf_buffer,
            pagesize=letter,
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36
        )
        styles = getSampleStyleSheet()

        title_style = ParagraphStyle(
            'TitleStyle',
            parent=styles['Heading1'],
            fontSize=22,
            leading=26,
            textColor=colors.HexColor("#1e293b"),
            spaceAfter=4
        )
        subtitle_style = ParagraphStyle(
            'SubTitleStyle',
            parent=styles['Normal'],
            fontSize=11,
            leading=14,
            textColor=colors.HexColor("#64748b"),
            spaceAfter=12
        )
        heading2_style = ParagraphStyle(
            'Heading2Style',
            parent=styles['Heading2'],
            fontSize=13,
            leading=17,
            textColor=colors.HexColor("#0f172a"),
            spaceBefore=8,
            spaceAfter=4
        )
        tip_style = ParagraphStyle(
            'TipStyle',
            parent=styles['Normal'],
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#4338ca"),
            spaceAfter=6
        )
        normal_style = ParagraphStyle(
            'NormalStyle',
            parent=styles['Normal'],
            fontSize=8.5,
            leading=11,
            textColor=colors.HexColor("#334155")
        )

        elements = []

        # Title
        dest = user_input.get("destination", "Vacation Destination").upper()
        elements.append(Paragraph(f"<b>{dest}</b> ITINERARY", title_style))
        elements.append(Paragraph(
            f"Origin: <b>{user_input.get('origin', 'N/A')}</b> &nbsp;|&nbsp; "
            f"Departure: <b>{user_input.get('departure_date') or 'Flexible'}</b> &nbsp;|&nbsp; "
            f"Duration: <b>{user_input.get('days', 1)} Days</b>",
            subtitle_style
        ))
        elements.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#2563eb"), spaceAfter=10))

        # Financial Summary Card Table
        budget_val = float(user_input.get("budget", 0))
        cost_val = float(itinerary.get("total_estimated_cost", 0))
        status_txt = "BUDGET APPROVED" if state.get("budget_approved") else "BUDGET EXCEEDED"
        status_color = "#16a34a" if state.get("budget_approved") else "#ea580c"

        summary_data = [
            [
                Paragraph(f"<b>Target Budget:</b> ${budget_val:,.2f}", normal_style),
                Paragraph(f"<b>Est. Total Cost:</b> ${cost_val:,.2f}", normal_style),
                Paragraph(f"<b>Status:</b> <font color='{status_color}'><b>{status_txt}</b></font>", normal_style)
            ],
            [
                Paragraph(f"<b>Transit:</b> ${cost_breakdown.get('flight', 0):,.2f}", normal_style),
                Paragraph(f"<b>Lodging:</b> ${cost_breakdown.get('lodging', 0):,.2f}", normal_style),
                Paragraph(f"<b>Activities & Dining:</b> ${cost_breakdown.get('activities', 0):,.2f}", normal_style)
            ]
        ]
        summary_table = Table(summary_data, colWidths=[180, 180, 180])
        summary_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#e2e8f0")),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ('TOPPADDING', (0, 0), (-1, -1), 6),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ]))
        elements.append(summary_table)
        elements.append(Spacer(1, 10))

        # Lodging & Flight Section
        flight = itinerary.get("selected_flight", {})
        hotel = itinerary.get("selected_hotel", {})
        logistics_text = (
            f"<b>Transit Option:</b> {flight.get('carrier', 'Flight')} ({flight.get('route', 'Direct')}) — "
            f"Est. ${flight.get('estimated_cost', 0):,.2f}<br/>"
            f"<b>Accommodation:</b> {hotel.get('name', 'Hotel')} ({hotel.get('tier', 'Comfort')}) in {hotel.get('neighborhood', 'City')} — "
            f"${hotel.get('nightly_rate', 0):,.2f}/night"
        )
        elements.append(Paragraph(logistics_text, normal_style))
        elements.append(Spacer(1, 10))

        # Days
        elements.append(Paragraph("Day-by-Day Schedule (Geographically Grouped)", heading2_style))
        for day in schedule:
            d_num = day.get("day")
            nb = day.get("neighborhood_focus", "Area")
            day_cost = float(day.get("estimated_cost", 0.0))
            elements.append(Paragraph(f"<b>Day {d_num}: {nb} District</b> &nbsp;—&nbsp; <font color='#2563eb'><b>Estimated Day Cost: ${day_cost:,.2f}</b></font>", heading2_style))
            if day.get("insider_tip"):
                elements.append(Paragraph(f"💡 {day.get('insider_tip')}", tip_style))

            day_rows = [["Time Slot", "Activity & Location", "Duration", "Cost"]]
            for ev in day.get("events", []):
                cost_str = f"${float(ev.get('estimated_cost', 0)):,.2f}" if float(ev.get("estimated_cost", 0)) > 0 else "Free"
                dur_str = f"{float(ev.get('duration_hours', 1.0)):.1f} hr"
                desc_txt = ev.get('description', '')
                desc_snippet = f"<br/><font color='#64748b'>{desc_txt[:90]}...</font>" if len(desc_txt) > 90 else f"<br/><font color='#64748b'>{desc_txt}</font>"
                activity_cell = Paragraph(
                    f"<b>{ev.get('name', 'Event')}</b> <font color='#64748b'>({ev.get('category', 'Activity')})</font><br/>"
                    f"<font color='#0284c7'>📍 {ev.get('location', nb)}</font>"
                    f"{desc_snippet}",
                    normal_style
                )
                day_rows.append([
                    Paragraph(ev.get("time_slot", "").replace(" - ", "<br/>"), normal_style),
                    activity_cell,
                    Paragraph(dur_str, normal_style),
                    Paragraph(cost_str, normal_style)
                ])
            t = Table(day_rows, colWidths=[90, 310, 60, 80])
            t.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
                ('TEXTCOLOR', (0, 0), (-1, 0), colors.HexColor("#334155")),
                ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
                ('FONTSIZE', (0, 0), (-1, -1), 8),
                ('VALIGN', (0, 0), (-1, -1), 'TOP'),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
                ('TOPPADDING', (0, 0), (-1, -1), 4),
                ('LINEBELOW', (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ]))
            elements.append(t)
            elements.append(Spacer(1, 6))

        doc.build(elements)
        pdf_buffer.seek(0)
        return pdf_buffer

    except Exception:
        # Fallback to simple text formatted output as binary stream
        txt = generate_text_itinerary(state)
        pdf_buffer.write(txt.encode("utf-8"))
        pdf_buffer.seek(0)
        return pdf_buffer
